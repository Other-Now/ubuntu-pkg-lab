"""results/*.jsonl -> results/SUMMARY.md"""
import glob
import json
import os
import statistics

os.chdir(os.path.join(os.path.dirname(__file__), "..", "results"))
lines = ["| run | identical | depsolve unsat but apt ok | both valid when different | apt unneeded pkgs (max) | depsolve unneeded (max) | largest set | depsolve ms median / max | backtracks (total) |",
         "|---|---|---|---|---|---|---|---|---|"]
for f in ["random-500.jsonl", "hard-500.jsonl", "curated.jsonl",
          "hard-500-ablation-priority-name.jsonl", "hard-500-ablation-name.jsonl"]:
    r = [json.loads(l) for l in open(f, encoding="utf-8")]
    diff = [x for x in r if not x["same"] and x["apt_ok"] and x["ds_ok"]]
    valid = sum(1 for x in diff if not x["apt_problems"] and not x["ds_problems"])
    ms = [x["ds_ms"] for x in r]
    lines.append(f"| {f[:-6]} | {sum(x['same'] for x in r)}/{len(r)} | "
                 f"{sum(1 for x in r if x['apt_ok'] and not x['ds_ok'])} | {valid}/{len(diff)} | "
                 f"{max([len(x['apt_unneeded']) for x in diff], default=0)} | "
                 f"{max([len(x['ds_unneeded']) for x in diff], default=0)} | {max(x['apt_n'] for x in r)} | "
                 f"{statistics.median(ms):.1f} / {max(ms):.0f} | {sum(x['backtracks'] for x in r)} |")
    for x in diff:
        lines.append(f"|   ↳ `{x['pkg']}` | apt {x['apt_n']} vs depsolve {x['ds_n']} | | "
                     f"{'valid' if not x['apt_problems'] and not x['ds_problems'] else 'INVALID'} | "
                     f"{len(x['apt_unneeded'])} | {len(x['ds_unneeded'])} | | | |")
open("SUMMARY.md", "w", newline="", encoding="utf-8").write(
    "# depsolve vs apt-get -s (noble main+universe amd64, empty dpkg status, --no-install-recommends)\n\n"
    "Generated by scripts/summarize.py.\n\n" + "\n".join(lines) + "\n")
print("\n".join(lines))
